; SND — задача ПВС на СМ-2: выдача пакета в БЭСМ-6 через Э-60.
; Прототип: src/wri/wri_src.txt:496–520 (кольцевой буфер, OUT FLD1..3).
; Минимальная версия: берёт результат из OUT FLD, пишет в буфер и
; инкрементирует номер пакета. CRC и двухфазная выдача — GAP.
; ---------------------------------------------------------------------------

            .ORG    0
START:      LDA     OUTFLD
            STA     RING
            LDA     NPACK
            ADA     ONE
            STA     NPACK
            HLT

; --- Буферы ----------------------------------------------------------------
            .ORG    000040
OUTFLD:     .WORD   54321       ; результат модели ПС
RING:       .WORD   0           ; слово кольцевого буфера
NPACK:      .WORD   0           ; номер пакета
ONE:        .WORD   1

            .END
