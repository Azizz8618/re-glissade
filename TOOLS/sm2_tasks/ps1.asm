; ---------------------------------------------------------------------------
; PS1 — первая задача тренажёра «Глиссада-6» на СМ-2.
;
; Взять из Area дескриптора поля PS значения NUM PS и PERIOD, сложить их,
; записать результат в OUT FLD и остановиться.
;
; Area дескриптора и OUT FLD заданы фиксированными адресами в нулевой
; странице (000000-000777), поэтому прямая адресация MRG работает без
; переключения страниц.
; ---------------------------------------------------------------------------

            .ORG    0

START:      LDA     NUM         ; A := NUM PS
            ADA     PERIOD      ; A := NUM PS + PERIOD
            STA     OUT         ; OUT FLD := A
            HLT                 ; останов

; --- Area дескриптора поля PS ---------------------------------------------

            .ORG    000010
NUM:        .WORD   5           ; NUM PS
PERIOD:     .WORD   7           ; PERIOD

; --- OUT FLD --------------------------------------------------------------

            .ORG    000012
OUT:        .WORD   0           ; результат: NUM PS + PERIOD

            .END
